import {build} from 'esbuild';
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  absWorkingDir: root, entryPoints: ['client-source.js'], outfile: 'client.js',
  bundle: true, format: 'iife', platform: 'browser', target: ['es2022'],
  minify: true, legalComments: 'external', write: false,
  banner: {js: '// Generated by scripts/build-client.mjs. Edit client-source.js / usage-chart*.js instead.'},
});
const check = process.argv.includes('--check');
for (const output of result.outputFiles) {
  if (check) {
    const current = await readFile(output.path).catch(() => null);
    if (!current?.equals(Buffer.from(output.contents))) throw new Error(`Stale client artifact: ${path.relative(root, output.path)}. Run npm run build.`);
  } else {
    await mkdir(path.dirname(output.path), {recursive: true});
    await writeFile(output.path, output.contents);
  }
}
console.log(check ? 'Client artifacts match source.' : 'Built local ECharts client bundle.');
